#!/usr/bin/env python3
"""Word-level timings from a voiceover, for captions that land as each word is spoken.

usage: word_cues.py <voiceover.wav|mp3|mp4> [--out assets/words.js] [--lead 0.08]

Writes window.WORDS = [{w:"Every", t:0.03, end:0.54}, ...] with t = spoken onset - lead (the
references land a word 0-4 frames BEFORE it is heard; 0.08 s is the default), plus window.LINES:
words grouped into lines at punctuation or pauses >= 0.25 s (one line = one on-screen beat).
Needs whisper-cli and a ggml model (~/.cache/*/whisper/models/ggml-*.bin or ~/.cache/*/ggml-*.bin).
"""
import argparse
import glob
import json
import os
import re
import subprocess
import tempfile


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("audio")
    ap.add_argument("--out", default="assets/words.js")
    ap.add_argument("--lead", type=float, default=0.08)
    a = ap.parse_args()
    models = sorted(glob.glob(os.path.expanduser("~/.cache/*/whisper/models/ggml-*.bin")) +
                    glob.glob(os.path.expanduser("~/.cache/*/ggml-*.bin")))
    if not models:
        raise SystemExit("no ggml whisper model found under ~/.cache")
    wav = tempfile.mktemp(suffix=".wav")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", a.audio, "-ac", "1", "-ar", "16000", wav], check=True)
    txt = subprocess.run(["whisper-cli", "-m", models[-1], "-f", wav, "-ml", "1", "-sow", "-np"],
                         capture_output=True, text=True).stdout
    os.remove(wav)
    ts = lambda h, m, s: int(h) * 3600 + int(m) * 60 + float(s)
    words = []
    for line in txt.splitlines():
        m = re.match(r"\[(\d+):(\d+):([\d.]+) --> (\d+):(\d+):([\d.]+)\]\s+(.*\S)", line.strip())
        if m and re.search(r"[A-Za-z0-9$]", m.group(7)):
            words.append({"w": m.group(7).strip(), "t": round(max(0, ts(*m.group(1, 2, 3)) - a.lead), 3),
                          "end": round(ts(*m.group(4, 5, 6)), 3)})
    lines, cur = [], []
    for i, w in enumerate(words):
        cur.append(i)
        gap = words[i + 1]["t"] - w["end"] if i + 1 < len(words) else 9
        if re.search(r"[.!?,:;]$", w["w"]) or gap >= 0.25:
            lines.append({"words": cur, "t": words[cur[0]]["t"], "end": w["end"]}); cur = []
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        f.write("// Generated by word_cues.py\nwindow.WORDS = " + json.dumps(words) + ";\nwindow.LINES = " + json.dumps(lines) + ";\n")
    secs = words[-1]["end"] - words[0]["t"] if words else 0
    print(f"{len(words)} words in {len(lines)} lines, {len(words) / max(secs, 1e-9):.2f} words/s -> {a.out}")


if __name__ == "__main__":
    main()
